export function getFeaturedItems(): MenuItem[] {
  return menuItems.filter(item => item.featured);
}

export function getItemsByCategory(categorySlug: string): MenuItem[] {
  if (categorySlug === 'all') return menuItems;
  return menuItems.filter(item => item.category === categorySlug);
}

export function getItemsByGoal(goalSlug: string): MenuItem[] {
  return menuItems.filter(item => item.goalTags.includes(goalSlug));
}

export function getItemBySlug(slug: string): MenuItem | undefined {
  return menuItems.find(item => item.slug === slug);
}
